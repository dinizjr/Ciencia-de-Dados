SELECT L.ID_LOJA,L.NOME_LOJA,L.LOCALIZACAO,
CONVERT(VARCHAR(15),(VD.DATA_VENDA), 103) [DATA VENDA],
PE.ID_VENDA,C.ID_CLIENTE,
C.NOME_CLIENTE,VE.ID_VENDEDOR,VE.NOME_VENDEDOR,
PR.ID_PRODUTO,PR.NOME_PRODUTO,PR.DESCRICAO_PRODUTO,
F.ID_FORNECEDOR,F.NOME_FORNECEDOR,
PE.QUANTIDADE,PR.VALOR_UNITARIO
FROM VENDAS VD
LEFT JOIN LOJAS L ON VD.ID_LOJA = L.ID_LOJA
LEFT JOIN PEDIDOS PE ON VD.ID_VENDA = PE.ID_VENDA
LEFT JOIN PRODUTOS PR ON PR.ID_PRODUTO = PE.ID_PRODUTO
LEFT JOIN FORNECEDORES F ON F.ID_FORNECEDOR = PR.ID_FORNECEDOR
LEFT JOIN CLIENTES C ON C.ID_CLIENTE = VD.ID_CLIENTE
LEFT JOIN VENDEDORES VE ON VE.ID_VENDEDOR = VD.ID_VENDEDOR
ORDER BY 1,VD.DATA_VENDA ASC

