USE DW_ABC
/* Tipos de dados */
CREATE TYPE TP_NOME FROM NVARCHAR(50) NOT NULL;
CREATE TYPE TP_TELEFONE FROM NVARCHAR(15);
GO

/* Cria tabela de lojas filiais (5) */
CREATE TABLE LOJAS (
	ID_LOJA INT IDENTITY(1,1),
	NOME_LOJA TP_NOME,
	LOCALIZACAO NVARCHAR(100),
	PRIMARY KEY (ID_LOJA)
);
GO

/* Cria tabela de funcionários vendedores (100) */
CREATE TABLE VENDEDORES (
	ID_VENDEDOR INT IDENTITY(1,1),
	NOME_VENDEDOR TP_NOME,
	DATA_ADMISSAO SMALLDATETIME,
	INSS BIGINT,
	PRIMARY KEY (ID_VENDEDOR)
);
GO

/* Cria tabela de fornecedores (50) */
CREATE TABLE FORNECEDORES (
	ID_FORNECEDOR INT IDENTITY(1,1),
	NOME_FORNECEDOR TP_NOME,
	RESPONSAVEL NVARCHAR(30),
	TELEFONE TP_TELEFONE,
	PRIMARY KEY (ID_FORNECEDOR)
);
GO

/* Cria tabela de produtos (200) */
CREATE TABLE PRODUTOS (
	ID_PRODUTO INT IDENTITY(1,1),
	ID_FORNECEDOR INT,
	NOME_PRODUTO TP_NOME,
	DESCRICAO_PRODUTO NVARCHAR(100),
	VALOR_UNITARIO MONEY,
	PRIMARY KEY (ID_PRODUTO),
	CONSTRAINT FK_PRODUTOS_FORNECEDORES FOREIGN KEY (ID_FORNECEDOR) REFERENCES FORNECEDORES (ID_FORNECEDOR)
);
GO

/* Cria tabela de clientes (100) */
CREATE TABLE CLIENTES (
	ID_CLIENTE INT IDENTITY(1,1),
	NOME_CLIENTE TP_NOME,
	LOGRADOURO NVARCHAR(100),
	CIDADE NVARCHAR(50),
	TELEFONE TP_TELEFONE,
	EMAIL NVARCHAR(50),
	PRIMARY KEY (ID_CLIENTE)
);
GO

/* Cria tabela de vendas efetuadas (8000) */
CREATE TABLE VENDAS (
	ID_VENDA INT IDENTITY(1,1),
	ID_VENDEDOR INT,
	ID_LOJA INT,
	ID_CLIENTE INT,
	DATA_VENDA SMALLDATETIME,
	PRIMARY KEY (ID_VENDA),
	CONSTRAINT FK_VENDAS_VENDEDORES FOREIGN KEY (ID_VENDEDOR) REFERENCES VENDEDORES (ID_VENDEDOR),
	CONSTRAINT FK_VENDAS_LOJAS FOREIGN KEY (ID_LOJA) REFERENCES LOJAS (ID_LOJA),
	CONSTRAINT FK_VENDAS_CLIENTES FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTES (ID_CLIENTE)
);
GO

/* Cria tabela de pedidos realizados (10000) */
CREATE TABLE PEDIDOS (
	ID_VENDA INT,
	ID_PRODUTO INT,
	QUANTIDADE INT,
	PRIMARY KEY (ID_VENDA, ID_PRODUTO),
	CONSTRAINT FK_PEDIDOS_VENDAS FOREIGN KEY (ID_VENDA) REFERENCES VENDAS (ID_VENDA),
	CONSTRAINT FK_PEDIDOS_PRODUTOS FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTOS (ID_PRODUTO)
);
GO

