
CREATE TABLE TARIFA (
                COD_TARIFA INT NOT NULL,
                RESTRCOES VARCHAR(30) NOT NULL,
                VALOR NUMERIC NOT NULL,
                CONSTRAINT COD_TARIFA PRIMARY KEY (COD_TARIFA)
)

CREATE TABLE RESERVA (
                COD_INSTTRECHO INT NOT NULL,
                POLTRONAS NUMERIC NOT NULL,
                NOME VARCHAR(30) NOT NULL,
                TELEFONE NUMERIC NOT NULL,
                CONSTRAINT COD_INSTTRECHO PRIMARY KEY (COD_INSTTRECHO, POLTRONAS)
)

CREATE TABLE PODE_POUSAR (
                TIPO_AERONAVE CHAR(10) NOT NULL,
                COD_AEROPORTO INT NOT NULL,
                CONSTRAINT TIPO_AERONAVE PRIMARY KEY (TIPO_AERONAVE, COD_AEROPORTO)
)

CREATE TABLE AERONAVE (
                COD_AERONAVE CHAR(10) NOT NULL,
                TIPO_AERONAVE CHAR(10) NOT NULL,
                NUM_POLTRONAS NUMERIC NOT NULL,
                EMPRESA VARCHAR(30) NOT NULL,
                DESCRICAO VARCHAR(30) NOT NULL,
                CONSTRAINT COD_AERONAVE PRIMARY KEY (COD_AERONAVE)
)

CREATE TABLE AEROPORTO (
                COD_AEROPORTO INT NOT NULL,
                NOME VARCHAR(30) NOT NULL,
                CIDADE VARCHAR(30) NOT NULL,
                ESTADO VARCHAR(30) NOT NULL,
                PAIS VARCHAR(30) NOT NULL,
                CONSTRAINT COD_AEROPORTO PRIMARY KEY (COD_AEROPORTO)
)

CREATE TABLE INSTANCIA_TRECHO (
                COD_INSTTRECHO INT NOT NULL,
                COD_AERONAVE INT NOT NULL,
                COD_AEROORG INT NOT NULL,
                COD_AERODST INT NOT NULL,
                DTTHORA_SAIDA DATETIME NOT NULL,
                DTTHORA_CHEGADA DATETIME NOT NULL,
                CONSTRAINT COD_INSTTRECHO PRIMARY KEY (COD_INSTTRECHO)
)

CREATE TABLE VOO (
                COD_VOO INT NOT NULL,
                COD_TARIFA INT NOT NULL,
                CONSTRAINT COD_VOO PRIMARY KEY (COD_VOO)
)

