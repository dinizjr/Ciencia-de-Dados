
CREATE TABLE TIPO_AERONAVE (
                ID_TIPO INT IDENTITY NOT NULL,
                DESCRICAO VARCHAR(100) NOT NULL,
                NUM_POLTRONAS SMALLINT NOT NULL,
                CONSTRAINT COD_TIPO_PK PRIMARY KEY (ID_TIPO)
)

CREATE TABLE TARIFA (
                ID_TARIFA INT IDENTITY NOT NULL,
                RESTRCOES VARCHAR(30) NOT NULL,
                VALOR NUMERIC NOT NULL,
                CONSTRAINT COD_TARIFA_PK PRIMARY KEY (ID_TARIFA)
)

CREATE TABLE AERONAVE (
                COD_AERONAVE VARCHAR(20) NOT NULL,
                EMPRESA VARCHAR(30) NOT NULL,
                DESCRICAO VARCHAR(50) NOT NULL,
                ID_TIPO INT NOT NULL,
                CONSTRAINT COD_AERONAVE_PK PRIMARY KEY (COD_AERONAVE)
)

CREATE TABLE AEROPORTO (
                COD_AEROPORTO CHAR(3) NOT NULL,
                NOME VARCHAR(100) NOT NULL,
                CIDADE VARCHAR(30) NOT NULL,
                ESTADO VARCHAR(30) NOT NULL,
                PAIS VARCHAR(30) NOT NULL,
                CONSTRAINT COD_AEROPORTO_PK PRIMARY KEY (COD_AEROPORTO)
)

CREATE TABLE PODE_POUSAR (
                COD_AEROPORTO CHAR(3) NOT NULL,
                ID_TIPO INT NOT NULL,
                CONSTRAINT COD_TIPO2_PK PRIMARY KEY (COD_AEROPORTO, ID_TIPO)
)

CREATE TABLE VOO (
                ID_VOO INT IDENTITY NOT NULL,
                ID_TARIFA INT NOT NULL,
                DIA_DA_SEMANA VARCHAR(20) NOT NULL,
                CONSTRAINT COD_VOO_PK PRIMARY KEY (ID_VOO)
)

CREATE TABLE TRECHO_VOO (
                ID_TRECHO INT IDENTITY NOT NULL,
                ID_VOO INT NOT NULL,
                HORASAIDA_PGM DATETIME NOT NULL,
                HORACHEGADA_PGM DATETIME NOT NULL,
                AEROSAIDA_PGM CHAR(3) NOT NULL,
                AEROCHEGA_PGM CHAR(3) NOT NULL,
                CONSTRAINT COD_TRECHO_PK PRIMARY KEY (ID_TRECHO, ID_VOO)
)

CREATE TABLE INSTANCIA_TRECHO (
                ID_INSTTRECHO INT IDENTITY NOT NULL,
                ID_TRECHO INT NOT NULL,
                DTTHORA_SAIDA DATETIME NOT NULL,
                DTTHORA_CHEGADA DATETIME NOT NULL,
                PLT_DISPONIVEIS NUMERIC NOT NULL,
                ID_VOO INT NOT NULL,
                AEROSAIDA CHAR(3) NOT NULL,
                AEROCHEGADA CHAR(3) NOT NULL,
                COD_AERONAVE VARCHAR(20) NOT NULL,
                CONSTRAINT COD_INSTTRECHO_PK PRIMARY KEY (ID_INSTTRECHO)
)

CREATE TABLE RESERVA (
                POLTRONA VARCHAR(5) NOT NULL,
                ID_INSTTRECHO INT NOT NULL,
                NOME VARCHAR(50) NOT NULL,
                TELEFONE NUMERIC NOT NULL,
                DESCRICAO VARCHAR(100) NOT NULL,
                CONSTRAINT COD_INSTTRECHO2_PK PRIMARY KEY (POLTRONA, ID_INSTTRECHO)
)

